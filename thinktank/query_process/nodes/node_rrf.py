from thinktank.query_process.base import NodeBase
from thinktank.query_process.state import QueryGraphState
from thinktank.tool.logger import logger
from thinktank.tool.json_format import json_format

class NodeRrf(NodeBase):
    """
    节点功能：Reciprocal Rank Fusion
    将多路召回的结果（向量、HyDE、Web）进行加权融合排序。
    步骤如下：
    (1) 得到两路检索后的结果数据，就是混合向量检索和 假设性文档检索的数据。
    (2) 然后给其赋值权重。
    (3) 通过循环的方式去遍历每个 检索结果，并和权重一起计算，得到对应id的分数，并将分数存储在字典中。
    (4) 然后将其通过分数进行覆盖即可。
    注意：关键在于这个算法。
    """

    # 覆盖基类的 name 属性，标识节点名称
    name: str = "node_rrf"

    def process(self, state: QueryGraphState):

        embedding_chunks = state.get("embedding_chunks")
        hyde_embedding_chunks = state.get("hyde_embedding_chunks")


        # rrf融合用自己的话说其实就是两件事：
        # (1) 去重（两路同时拥有某一个chunk，最终融合到一路只有一个这个chunk,只是分数是两路的和）
        # (2) 筛选，最终只要10个 rrf融合条件 一般都是数据来源相同但是量纲不同。

        # 1、先对两路数据设置权重值
        weight_chunks = [
            (embedding_chunks,1),
            (hyde_embedding_chunks,1)
        ]

        # 2、遍历每一路获取到 chunk 根据公式计算排名分数，而不关心本身chunk当中的score
        rrf_dict = {}

        # 这个for循环能到的结果是什么？
        # 先循环这个内容：(embedding_chunks,1)
        # 再循环这个内容：(hyde_embedding_chunks,1)
        for chunks, weight in weight_chunks:
            for idx, chunk in enumerate(chunks,start=1):
                # 得到每个chunk的id

                id = chunk.get("id")

                # 计算出每个id的排名分数
                score = weight / (idx + 60)

                if id in rrf_dict:
                    #已经存在了，分数累加即可
                    rrf_dict[id]['score'] += score
                else:
                    # 使用新计算出来的倒数得分覆盖原来的向量检索分数
                    chunk["score"] = score     
                    rrf_dict[id] = chunk   # 得到的每个id 对应的 chunk，关键是chunk内容中的分数已经完成覆盖

        # 在 进行排序即可。
        rrf_chunks = sorted(rrf_dict.values(),key=lambda x:x["score"],reverse=True)[:10]

        return {
            "rrf_chunks":rrf_chunks
        }

