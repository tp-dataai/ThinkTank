from thinktank.query_process.base import NodeBase
from thinktank.query_process.state import QueryGraphState
from thinktank.tool.logger import logger
from thinktank.tool.reranker_tool import text_rerank
from thinktank.tool.json_format import json_format

class NodeRerank(NodeBase):
    """
    节点功能：使用 Cross-Encoder 模型对 RRF 后的结果进行精确打分重排。
    处理步骤：
    (1) 获取数据: rrf排序后的数据和mcp返回的数据,以及问题。并对数据进行整理。
    (2) 模型重排: 使用 Cross-Encoder 进行重排序。
                -> 使用 qwen3.7-text-rerank
    (3) 断崖检测: 数据变化最大的地方就是断崖(通过断崖检测算法获取动态top-k)
                -> 绝对断崖 = 当前位置的分数 - 下一个位置的分数  注意：(从数量上来看)
                -> 相对断崖 = (当前位置的分数 - 下一个位置的分数) / 当前位置的分数   注意：(从数据相对变化来看)
    """

    # 覆盖基类的 name 属性，标识节点名称
    name: str = "node_rerank"

    def process(self, state: QueryGraphState):
        rrf_chunks = state.get("rrf_chunks") or []
        web_search_docs = state.get("web_search_docs") or []
        rewritten_query = state.get("rewritten_query") or ""

        merged_chunks = rrf_chunks + web_search_docs
        merged_chunks = [
            {
                "content": item.get("content"),
                "title": item.get("item_name") or item.get("title"),
                "url": item.get("url") or "",
                "source": item.get("source"),
            }
            for item in merged_chunks
        ]

        # 关键修复：过滤空 content（上次 400 的根因）
        merged_chunks = [c for c in merged_chunks if c.get("content") and c["content"].strip()]

        if not merged_chunks or not rewritten_query.strip():
            logger.warning("rerank 输入为空，跳过重排")
            return {"reranked_docs": []}

        merged_chunks_str_list = [c["content"] for c in merged_chunks]
        res = text_rerank(query=rewritten_query, documents=merged_chunks_str_list)

        for item in res:
            idx = item.get("index")
            score = item.get("score")
            if idx is None or score is None or idx >= len(merged_chunks):
                continue
            merged_chunks[idx]["score"] = score

        rerank_chunks = sorted(merged_chunks, key=lambda x: x.get("score", 0.0), reverse=True)

        RERANK_MAX_TOPK = 18
        RERANK_GAP_RATIO = 0.25
        RERANK_GAP_ABS = 0.1
        use_max_topk = min(RERANK_MAX_TOPK, len(rerank_chunks))
        break_idx = use_max_topk

        # 关键修复：只在前 use_max_topk 内扫描，i+1 不会越界，break_idx 不会超上限
        for i in range(use_max_topk - 1):
            current_score = rerank_chunks[i].get("score", 0.0)
            next_score = rerank_chunks[i + 1].get("score", 0.0)
            gap_abs = current_score - next_score
            gap_ratio = gap_abs / (current_score + 1e-6)
            if gap_abs > RERANK_GAP_ABS or gap_ratio > RERANK_GAP_RATIO:
                break_idx = i + 1
                break

        return {"reranked_docs": rerank_chunks[:break_idx]}



