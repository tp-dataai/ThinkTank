# 进程：程序的一次执行运行过程。进程是动态的，进程占有内存、cpu等等一些资源，随着进程的执行是在变化的

# 线程：是计算调度的最小单元，用自己的话来说线程就是执行代码的人。因此进程至少有一个线程（主线程）


# GIL：全局解释器锁，这个锁的存在意义是保证底层分配内存的时候安全性。我们学习的线程锁它是上层业务锁
# 总规都是为了不让同一个资源被多个人争抢。GIL的出现会让同一时刻只能有一个线程执行代码。每个进程都有自己的gil锁
# 只有python当中有这个。

# GIL锁释放条件2个：
# 1、碰到io阻塞立即释放
# 2、如果没有io阻塞，底层会执行完100条字节码指令，立即释放锁


