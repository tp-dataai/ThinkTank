# http:超文本传输协议，是前后端进行数据交互所遵循的规范。
# http协议是基于底层tcp协议的，所以是一个可靠型协议
# http协议最终其实就是报文：前后端规定好，发啥反啥  请求报文 响应报文
# 报文的格式： 行 头 空行 体 组成一个大的字符串
#
# 我们开发人员我们并不关心整个报文的所有信息，我们只关心报文的主要信息*****
#
# 作为前端人员
#     发请求
#         1、请求地址
#         2、请求参数（文件）
#         3、请求方式     get post put delete
#         4、请求头信息   token cookie session 做用户登录态校验
#
#     拿响应
#         获取后端返回给前端的响应，我们关心的是返回的数据和状态
#         http状态码 100 200 300 400 500
#
# 作为后端人员
#     接请求
#         1、接参数（路径 查询 请求体）
#         2、接头信息 接收前端传递的校验信息 token cookie session
#         3、接文件 上传文件
#
#     返响应
#         1、json
#         2、文件 下载文件
#         3、返流 sse(流式输出给前端，答案以打字机效果出现)  *******
#         4、返回其它：重定向 html页面 纯文本等等（后期几乎不用，前后端不分离的时候用的多）
#
# 前后端分离和不分离的概念
#     fastapi讲
